/* 画数末尾 → 五行 */
function gogyoOf(n){
  const d = n % 10;
  if (d === 1 || d === 2) return "木";
  if (d === 3 || d === 4) return "火";
  if (d === 5 || d === 6) return "土";
  if (d === 7 || d === 8) return "金";
  return "水"; // 9, 0
}
/* 相生（生かし合う） */
function isSousei(a, b){
  const cycle = { "木":"火", "火":"土", "土":"金", "金":"水", "水":"木" };
  return cycle[a] === b || cycle[b] === a;
}
/* 相剋（抑え合う） */
function isSoukoku(a, b){
  const koku = { "木":"土", "土":"水", "水":"火", "火":"金", "金":"木" };
  return koku[a] === b || koku[b] === a;
}

